#!/usr/bin/env python3
"""Write problems/MHD/shockCloudDaiWoodward1998/mhd_letters.jl: the dense letters "MHD" of
Dai & Woodward (1998, JCP 142:331, Fig. 20) as polygons in the domain's coordinates.

The letters of Fig. 20 are Times Bold. The glyphs M, H, D of Liberation Serif Bold (metric-compatible
with Times) are flattened, scaled to the cap height measured on the figure's first panel and placed
where that panel has them (the overlay of the outlines on the scan matches H and D to a pixel).

    python3 tools/shock_cloud_letters.py [--font LiberationSerif-Bold.ttf] [--nq 6]

Needs fontTools.
"""
import argparse
import os

from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen

# Measured on Fig. 20, panel t = 0.02507 (200 dpi scan, 479 x 355 px for the 2 x 1.5 domain).
Y_BASE, Y_CAP = 0.5746, 0.9697
PLACE = (("M", "right", 0.7850),   # the left of the M is already swept by the shock: place it by its right edge
         ("H", "left", 0.8142),
         ("D", "left", 1.2839))
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "problems", "MHD",
                   "shockCloudDaiWoodward1998", "mhd_letters.jl")


def contours(font, ch, nq):
    """The glyph's closed contours in font units, quadratic arcs split into nq segments."""
    pen = RecordingPen()
    font.getGlyphSet()[font.getBestCmap()[ord(ch)]].draw(pen)
    out, cur = [], []
    for op, args in pen.value:
        if op == "moveTo":
            cur = [args[0]]
        elif op == "lineTo":
            cur.append(args[0])
        elif op == "qCurveTo":            # TrueType: on-curve points implied midway between off-curve ones
            offs, end = args[:-1], args[-1]
            for i, o in enumerate(offs):
                a = cur[-1]
                b = end if i == len(offs) - 1 else ((o[0] + offs[i + 1][0])/2, (o[1] + offs[i + 1][1])/2)
                for k in range(1, nq + 1):
                    t = k/nq
                    cur.append(((1 - t)**2*a[0] + 2*t*(1 - t)*o[0] + t*t*b[0],
                                (1 - t)**2*a[1] + 2*t*(1 - t)*o[1] + t*t*b[1]))
        elif op in ("closePath", "endPath"):
            if cur[0] == cur[-1]:
                cur = cur[:-1]
            out.append(cur)
            cur = []
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", default="/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf")
    ap.add_argument("--nq", type=int, default=6, help="segments per quadratic arc")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()

    font = TTFont(a.font)
    s = (Y_CAP - Y_BASE)/font["OS/2"].sCapHeight
    lines = ["#" + "-"*81,
             '# The three dense clouds "MHD" of Dai & Woodward (1998, JCP 142:331, Fig. 20), as polygons in the',
             "# domain's coordinates. Generated by tools/shock_cloud_letters.py; do not edit by hand.",
             "#",
             "# The letters of Fig. 20 are Times Bold: the glyphs M, H, D of Liberation Serif Bold (Times-metric) are",
             f"# flattened ({a.nq} segments per quadratic arc), scaled to the cap height measured on the figure's first panel",
             f"# (t = 0.02507; base y = {Y_BASE}, cap line y = {Y_CAP}) and placed there: H from x = {PLACE[1][2]}, D from",
             f"# x = {PLACE[2][2]}, M ending at x = {PLACE[0][2]} (its left side is already swept by the shock in that panel).",
             "# One tuple of 2×n contours per letter; D's second contour is its counter. Inside = odd number of crossings.",
             "#" + "-"*81,
             "if !@isdefined(SC_LETTERS)",
             "    const SC_LETTERS = ("]
    for ch, side, x in PLACE:
        cs = contours(font, ch, a.nq)
        xs = [p[0] for c in cs for p in c]
        ox = x - s*(min(xs) if side == "left" else max(xs))
        lines += [f"        # {ch}", "        ("]
        for c in cs:
            lines.append("            [" + " ".join(f"{ox + s*px:.5f}" for px, _ in c) + ";")
            lines.append("             " + " ".join(f"{Y_BASE + s*py:.5f}" for _, py in c) + "],")
        lines.append("        ),")
    lines += ["    )", "end"]
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(a.out))


if __name__ == "__main__":
    main()
