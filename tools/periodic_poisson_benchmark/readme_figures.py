#!/usr/bin/env python3
"""Put the figures and the table of a benchmark run into README.md.

    python3 tools/periodic_poisson_benchmark/readme_figures.py [outdir]

`outdir` is the directory given to pipeline.jl (default: ppb_highres). This
script
  1. copies every SVG in <outdir>/assets/ into assets/<name of outdir>/;
  2. writes a README section with the results table (<outdir>/results.md),
     the error-versus-N_g figure of all levels (ppb_error_vs_Ng), the
     h-refinement figures (ppb_hrefine_*_N<N>) and the per-level figures
     (ppb_error_vs_*_L<L>), each figure with its dark-mode variant.

The section sits between two marker comments. Running the script again
replaces it, so rerun it after every new benchmark run. The first time, the
section is inserted before the "## Laguerre semi-infinite element test suite"
heading, at the end of the periodic Poisson benchmark section; if that heading
is missing, at the end of the README.

Each output directory gets its own figure folder and its own README section
(its own markers), so separate runs, e.g. a 1-level and a 3-level one, keep
separate sets of plots:
    python3 tools/periodic_poisson_benchmark/readme_figures.py ppb_1level
    python3 tools/periodic_poisson_benchmark/readme_figures.py ppb_3level

Run it from the repository root; no dependencies. Options:
    --readme PATH    README to edit (default README.md)
    --title TEXT     heading of the section (default: from the run)
"""
import csv, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

args = sys.argv[1:]
readme = os.path.join(ROOT, "README.md")
if "--readme" in args:
    i = args.index("--readme")
    readme = os.path.abspath(args[i + 1])
    del args[i:i + 2]
title = None
if "--title" in args:
    i = args.index("--title")
    title = args[i + 1]
    del args[i:i + 2]
outdir = os.path.abspath(args[0] if args else os.path.join(ROOT, "ppb_highres"))
name = os.path.basename(os.path.normpath(outdir))
src_assets = os.path.join(outdir, "assets")
dst_rel = f"assets/{name}"                       # as referenced from README.md
dst_assets = os.path.join(ROOT, dst_rel)
BEGIN = f"<!-- {name}:begin — generated by tools/periodic_poisson_benchmark/readme_figures.py; rerun it instead of editing -->"
END = f"<!-- {name}:end -->"
ANCHOR = "## Laguerre semi-infinite element test suite"

if not os.path.isdir(src_assets):
    sys.exit(f"readme_figures.py: no {src_assets} (run pipeline.jl with outdir = \"{outdir}\" first)")

# ---- 1. copy the figures ------------------------------------------------------
os.makedirs(dst_assets, exist_ok=True)
svgs = sorted(f for f in os.listdir(src_assets) if f.endswith(".svg"))
for f in svgs:
    shutil.copy2(os.path.join(src_assets, f), os.path.join(dst_assets, f))
print(f"copied {len(svgs)} SVG files to {dst_rel}/")
light = {f[:-4] for f in svgs if not f.endswith("-dark.svg")}

# ---- what the run contains --------------------------------------------------------
rows = []
csvpath = os.path.join(outdir, "results.csv")
if os.path.isfile(csvpath):
    with open(csvpath) as fh:
        rows = list(csv.DictReader(fh))
levels = sorted({int(r.get("level", 0) or 0) for r in rows}) or \
         sorted({int(m.group(1)) for f in light for m in [re.search(r"_L(\d+)$", f)] if m})
nel = {}
for r in rows:
    L = int(r.get("level", 0) or 0)
    nel[L] = int(r["nel"]) if r.get("nel") else round(int(r["dofs"]) ** 0.5 / int(r["nop"]))
nops = sorted({int(r["nop"]) for r in rows})
hrefine_n = sorted({int(m.group(1)) for f in light for m in [re.search(r"^ppb_hrefine_\w+_N(\d+)$", f)] if m})


def picture(stem, alt):
    if stem not in light:
        return ""
    dark = f"{dst_rel}/{stem}-dark.svg" if f"{stem}-dark.svg" in svgs else f"{dst_rel}/{stem}.svg"
    return (f'<picture>\n'
            f'  <source media="(prefers-color-scheme: dark)" srcset="{dark}">\n'
            f'  <img src="{dst_rel}/{stem}.svg" width="680" alt="{alt}">\n'
            f'</picture>\n\n')


def elements(L):
    n = nel.get(L, 16 * 2 ** L)
    return f"{n}×{n}"


# ---- 2. the README section ----------------------------------------------------
if title is None:
    if len(levels) > 1:
        title = f"Benchmark with mesh refinement, {len(levels)} levels ({elements(levels[0])} to {elements(levels[-1])} elements)"
    elif levels:
        title = f"Benchmark on the {elements(levels[0])} mesh"
    else:
        title = f"Benchmark run {name}"
o = [BEGIN, f"\n\n### {title}\n\n"]
if levels:
    o.append("The same six solvers"
             + (", with the 16×16 mesh refined uniformly through `:linitial_refine`: " if len(levels) > 1 else ": ")
             + ", ".join(f"level {L} = {elements(L)} elements" for L in levels)
             + (f", SEM orders N = {nops[0]}…{nops[-1]}" if nops else "")
             + ". The Fourier grids have the same number of unknowns, (16·2^L·N)². "
               "Timings follow the protocol above (second run in one Julia session). "
               f"Produced by `pipeline.jl` with `outdir = \"{name}\"`; see "
               "[tools/periodic_poisson_benchmark/README.md](tools/periodic_poisson_benchmark/README.md).\n\n")

mdpath = os.path.join(outdir, "results.md")
if os.path.isfile(mdpath):
    table = open(mdpath).read().strip()
    o.append("<details>\n<summary>Results table (all configurations)</summary>\n\n"
             + table + "\n\n</details>\n\n")

if "ppb_error_vs_Ng" in light:
    o.append("#### Error versus the Fourier grid size, all levels\n\n"
             "Every level on one axis: N_g = (elements per side) × N points per direction, the resolution of "
             "the Fourier solvers. Their error follows the predicted r^(N_g/2) (dashed) on every mesh, then "
             "flattens at the round-off floor, higher for the pseudo-spectral solver (dense eigen-decomposition "
             "and matrix products) than for the FFT. The SEM has one curve per mesh.\n\n")
    o.append(picture("ppb_error_vs_Ng",
                     "L-infinity error versus N_g, the number of points per direction, for all mesh levels: one SEM "
                     "curve per mesh; the pseudo-spectral and FFT errors follow the predicted 0.8^(N_g/2) and then "
                     "flatten at their round-off floors."))

if hrefine_n:
    o.append("#### Time versus unknowns under mesh refinement\n\n"
             "At fixed SEM order N, one curve per solver as the mesh is refined: where the AMG curves "
             "cross the direct-solve curves, if they do. *Cost* is the solver's own setup plus solve, "
             "without the SEM infrastructure; *total* is the time-to-solution including it.\n\n")
    what = {"solve": "the solve step", "cost": "setup plus solve (solver cost)",
            "total": "the time-to-solution including all infrastructure"}
    for n in hrefine_n:
        o.append(f"**SEM order N = {n}**\n\n")
        for key in ("solve", "cost", "total"):
            o.append(picture(f"ppb_hrefine_{key}_N{n}",
                             f"Wall-clock of {what[key]} versus number of unknowns under uniform mesh "
                             f"refinement at SEM order {n}, one curve per solver."))

if levels:
    o.append("#### Error and time at each mesh level\n\n" if len(levels) > 1 else "")
    for L in levels:
        # a multi-level run names them ppb_error_vs_*_L<L>; a single-level run has no suffix
        sfx = f"_L{L}" if f"ppb_error_vs_order_L{L}" in light else ""
        block = "".join([
            picture(f"ppb_error_vs_order{sfx}",
                    f"L-infinity error versus SEM order N on the {elements(L)} mesh (one SEM curve for its "
                    f"four solvers), with the pseudo-spectral and FFT solvers at the same number of unknowns."),
            picture(f"ppb_error_vs_dofs{sfx}",
                    f"L-infinity error versus number of unknowns on the {elements(L)} mesh."),
            picture(f"ppb_error_vs_solve_time{sfx}",
                    f"L-infinity error versus the wall-clock of the solve step on the {elements(L)} mesh, "
                    f"for the six solvers."),
            picture(f"ppb_error_vs_total_time{sfx}",
                    f"L-infinity error versus time-to-solution including all infrastructure on the "
                    f"{elements(L)} mesh, for the six solvers."),
        ])
        if block:
            o.append((f"**Level {L}: {elements(L)} elements**\n\n" if len(levels) > 1 else "") + block)

o.append(END)
section = "".join(o).rstrip() + "\n"
section = section.replace("\n\n" + END, "\n" + END)

text = open(readme).read()
if BEGIN.split(" — ")[0] in text and END in text:
    start = text.index(BEGIN.split(" — ")[0])
    stop = text.index(END) + len(END)
    text = text[:start] + section.rstrip("\n") + text[stop:]
    how = "replaced the existing section"
elif ANCHOR in text:
    i = text.index(ANCHOR)
    text = text[:i] + section + "\n" + text[i:]
    how = f"inserted a new section before \"{ANCHOR}\""
else:
    text = text.rstrip("\n") + "\n\n" + section
    how = "appended a new section at the end"
open(readme, "w").write(text)
nfig = section.count("<picture>")
print(f"{os.path.relpath(readme, ROOT)}: {how} ({nfig} figures)")
